export interface PdfFooter {
  company: string;
  ref: string;
  locale: L;
}

export interface PdfRenderer {
  render(html: string, footer: PdfFooter): Promise<Buffer>;
}

/** Footer for every page: company · report reference · page X of Y, laid out in the report's direction. */
export function footerHtml(f: PdfFooter): string {
  const rtl = f.locale === 'ar';
  const page = rtl
    ? 'صفحة <span class="pageNumber"></span> من <span class="totalPages"></span>'
    : 'Page <span class="pageNumber"></span> of <span class="totalPages"></span>';
  return `<div dir="${rtl ? 'rtl' : 'ltr'}" style="font-size:7pt;width:100%;text-align:center;color:#8c959f;font-family:sans-serif">${esc(f.company)} · <span dir="ltr">${esc(f.ref)}</span> · ${page}</div>`;
}

/** Headless Chromium via playwright-core (system Chromium; no browser download). */
export class ChromiumPdfRenderer implements PdfRenderer {
  constructor(
    private readonly executablePath: string | undefined,
    private readonly timeoutMs: number,
  ) {}

  async render(html: string, footer: PdfFooter): Promise<Buffer> {
    const { chromium } = await import('playwright-core');
    const browser = await chromium.launch({
      executablePath: this.executablePath,
      args: ['--no-sandbox', '--disable-dev-shm-usage', '--disable-gpu'],
      timeout: this.timeoutMs,
    });
    try {
      const context = await browser.newContext({ javaScriptEnabled: false, offline: true });
      const page = await context.newPage();
      page.setDefaultTimeout(this.timeoutMs);
      // Reports are fully self-contained: block any network request defensively.
      await page.route('**/*', (route) => (route.request().url().startsWith('data:') ? route.continue() : route.abort()));
      await page.setContent(html, { waitUntil: 'load', timeout: this.timeoutMs });
      return await page.pdf({
        format: 'A4',
        printBackground: true,
        displayHeaderFooter: true,
        headerTemplate: '<span></span>',
        footerTemplate: footerHtml(footer),
        margin: { top: '16mm', bottom: '18mm', left: '12mm', right: '12mm' },
      });
    } finally {
      await browser.close();
    }
  }
}

/**
 * Renders a queued report (idempotent: READY jobs are skipped; a RENDERING job older than 10 min is
 * retried). The dataset was authorized by the API; the worker never widens it.
 */
export async function processReport(prisma: PrismaClient, store: ObjectStore, renderer: PdfRenderer, notifier: Notifier, reportId: string): Promise<void> {
  const claim = await prisma.reportJob.updateMany({
    where: { id: reportId, OR: [{ status: 'QUEUED' }, { status: 'FAILED' }, { status: 'RENDERING', startedAt: { lt: new Date(Date.now() - 10 * 60_000) } }] },
    data: { status: 'RENDERING', startedAt: new Date(), error: null },
  });
  if (claim.count === 0) return; // already rendered / in progress / deleted
  const job = await prisma.reportJob.findUniqueOrThrow({ where: { id: reportId } });
  try {
    if (!job.dataset) throw new Error('report dataset missing');
    const ds = job.dataset as unknown as ReportDataset;
    const html = renderReportHtml(ds);
    const pdf = await renderer.render(html, { company: ds.companyName, ref: job.id.slice(0, 8), locale: ds.locale });
    const key = `reports/${job.companyId}/${job.id}.pdf`;
    await store.put(key, pdf, 'application/pdf');
    // The dataset is dropped once rendered (it may contain private rating data).
    await prisma.reportJob.update({ where: { id: job.id }, data: { status: 'READY', storageKey: key, sizeBytes: pdf.length, completedAt: new Date(), dataset: Prisma.DbNull } });
    await notifier.notify({ type: NotificationType.REPORT_READY, recipients: [job.requestedById], dedupeKey: `REPORT_READY:${job.id}`, url: '/reports' });
    logger.info('report rendered', { reportId: job.id, type: job.type, bytes: pdf.length });
  } catch (e) {
    await prisma.reportJob.update({ where: { id: job.id }, data: { status: 'FAILED', error: errMsg(e).slice(0, 500) } });
    logger.error('report rendering failed', { reportId: job.id, error: errMsg(e) });
    throw e; // SQS retries; the claim above allows FAILED to be retried
  }
}

/** Deletes expired reports (object + row). */
export async function cleanupExpiredReports(prisma: PrismaClient, store: ObjectStore, now = new Date()): Promise<number> {
  const rows = await prisma.reportJob.findMany({ where: { expiresAt: { lt: now } }, select: { id: true, storageKey: true }, take: 200 });
  let n = 0;
  for (const r of rows) {
    try {
      if (r.storageKey) await store.delete(r.storageKey);
      n += (await prisma.reportJob.deleteMany({ where: { id: r.id } })).count;
    } catch (e) {
      logger.warn('report cleanup failed', { reportId: r.id, error: errMsg(e) });
    }
  }
  return n;
}
